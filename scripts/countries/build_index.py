"""Writes src/components/countries/list.ts (browser-safe index) from the finished country copy files."""
import json, os, glob, re, unicodedata
HERE=os.path.dirname(os.path.abspath(__file__)); DATA=os.path.join(HERE,"../../src/components/countries/data")
NEED=["title","description","h1","sub","uses","steps","chapters","faq","ui","images"]
rows=[]
for f in glob.glob(os.path.join(DATA,"*.json")):
    d=json.load(open(f))
    if any(not d.get(k) for k in NEED): print("skip",d.get("code")); continue
    en=d.get("nameEn") or d["name"]; en=re.sub(r"^the ","",en,flags=re.I)
    slug=re.sub(r"[^a-z0-9]+","-",unicodedata.normalize("NFKD",en).encode("ascii","ignore").decode().lower()).strip("-")
    rows.append({"code":d["code"],"slug":slug,"name":d["name"],"nameEn":en,"lang":d["lang"]})
rows.sort(key=lambda r:r["nameEn"])
out="/** Generated by scripts/countries/build_index.py — every country page: /countries/<slug>, in the country's own language. */\nexport type CountryPage = { code: string; slug: string; name: string; nameEn: string; lang: string };\nexport const COUNTRY_PAGES: CountryPage[] = "+json.dumps(rows,ensure_ascii=False)+";\n"
open(os.path.join(HERE,"../../src/components/countries/list.ts"),"w").write(out); print(len(rows))
